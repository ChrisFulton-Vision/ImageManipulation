def load_navcalcs(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    if "image_time" not in df.columns:
        raise ValueError(f"{path} does not contain an image_time column.")
    df = df.copy()
    df["image_time"] = pd.to_numeric(df["image_time"], errors="coerce")
    df = df[np.isfinite(df["image_time"])].sort_values("image_time").reset_index(drop=True)
    return prepare_navcalcs_sync_time(df)


def load_novatel_tspi(path: Path) -> pd.DataFrame:
    """Load whitespace-delimited 28-column TSPI/DGPS data.

    Column mapping follows the user-provided header table:
        1  GPS time of week
        5  Vector Base to Rover ECEF-X Location
        7  Vector Base to Rover ECEF-Y Location
        9  Vector Base to Rover ECEF-Z Location
        28 GPS week
    """
    df = pd.read_csv(path, sep=r"\s+", header=None, comment="#", engine="python")
    if df.shape[1] < 28:
        raise ValueError(f"Expected at least 28 TSPI columns; found {df.shape[1]} in {path}")

    names = [
        "gps_tow",
        "rover_ecef_x", "rover_ecef_y", "rover_ecef_z",
        "base_to_rover_ecef_x", "base_to_rover_ecef_x_std",
        "base_to_rover_ecef_y", "base_to_rover_ecef_y_std",
        "base_to_rover_ecef_z", "base_to_rover_ecef_z_std",
        "ecef_vx", "ecef_vx_std",
        "ecef_vy", "ecef_vy_std",
        "ecef_vz", "ecef_vz_std",
        "gps_satellites", "quality_number", "ddop", "ca_rms", "l1_rms", "double_difference_dop",
        "fwd_rev_sep_east", "fwd_rev_sep_north", "fwd_rev_sep_height",
        "forward_combined_weighting", "reverse_combined_weighting", "gps_week",
    ]
    out = df.iloc[:, :28].copy()
    out.columns = names
    for c in out.columns:
        out[c] = pd.to_numeric(out[c], errors="coerce")
    out["truth_sync_time_s"] = out["gps_week"] * GPS_WEEK_SECONDS + out["gps_tow"]
    out = out[np.isfinite(out["truth_sync_time_s"])].sort_values("truth_sync_time_s").reset_index(drop=True)
    return out


def merge_probe_tanker_truth(
    probe: pd.DataFrame,
    tanker: pd.DataFrame,
    tspi: pd.DataFrame,
    sync_tolerance: float,
) -> pd.DataFrame:
    probe = probe.sort_values("sync_time_s").reset_index(drop=True)
    tanker = tanker.sort_values("sync_time_s").reset_index(drop=True)
    tspi = tspi.sort_values("truth_sync_time_s").reset_index(drop=True)

    merged = pd.merge_asof(
        probe,
        tanker,
        on="sync_time_s",
        direction="nearest",
        tolerance=sync_tolerance,
        suffixes=("_probe", "_tanker"),
    )

    # Track tanker synchronization residual if the original column survived via suffixes.
    # With merge_asof(on='sync_time_s'), both rows share the selected key. This is fine for
    # first-pass analysis because both navcalcs files are normally generated from the same
    # image clock.
    merged = pd.merge_asof(
        merged.sort_values("sync_time_s"),
        tspi,
        left_on="sync_time_s",
        right_on="truth_sync_time_s",
        direction="nearest",
        tolerance=sync_tolerance,
    )
    merged["truth_time_error_s"] = merged["sync_time_s"] - merged["truth_sync_time_s"]
    return merged.reset_index(drop=True)


