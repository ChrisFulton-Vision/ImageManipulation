def spec_available_for_object(df: pd.DataFrame, spec: PoseSpec, suffix: str) -> bool:
    valid_col, q_cols, t_cols = spec_cols(spec, suffix)
    return have_cols(df, [valid_col, *q_cols, *t_cols])


def spec_available_for_vector(df: pd.DataFrame, spec: PoseSpec) -> bool:
    return spec_available_for_object(df, spec, "probe") and spec_available_for_object(df, spec, "tanker")


def pose_arrays(df: pd.DataFrame, spec: PoseSpec, suffix: str) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    valid_col, q_cols, t_cols = spec_cols(spec, suffix)
    q = numeric(df, q_cols)
    t = numeric(df, t_cols)
    valid = as_bool(df[valid_col]) & finite_rows(q) & finite_rows(t)
    return q, t, valid


def compute_vision_vectors(
    df: pd.DataFrame,
    specs: Sequence[PoseSpec],
    receiver_probe_to_antenna: np.ndarray,
    tanker_center_to_antenna: np.ndarray,
) -> pd.DataFrame:
    out = df.copy()

    for spec in specs:
        q_probe, t_probe, valid_probe = pose_arrays(out, spec, "probe")
        q_tanker, t_tanker, valid_tanker = pose_arrays(out, spec, "tanker")

        R_probe = quat_to_rotmat_batch(q_probe)
        R_tanker = quat_to_rotmat_batch(q_tanker)

        p_receiver_ant = t_probe + rotate_vectors_batch(R_probe, receiver_probe_to_antenna)
        p_tanker_ant = t_tanker + rotate_vectors_batch(R_tanker, tanker_center_to_antenna)
        vision_vec = p_tanker_ant - p_receiver_ant

        valid = valid_probe & valid_tanker & finite_rows(p_receiver_ant) & finite_rows(p_tanker_ant) & finite_rows(vision_vec)

        for i, axis in enumerate("xyz"):
            out[f"{spec.key}_receiver_ant_{axis}"] = p_receiver_ant[:, i]
            out[f"{spec.key}_tanker_ant_{axis}"] = p_tanker_ant[:, i]
            out[f"{spec.key}_vision_vec_{axis}"] = vision_vec[:, i]
        out[f"{spec.key}_vision_range"] = vector_norm(vision_vec)
        out[f"{spec.key}_truth_compare_valid"] = valid

        # Range sigma from translational sigmas only. This deliberately ignores
        # lever-arm orientation covariance; it is still useful as a conservative
        # diagnostic when FG translational covariance is the dominant term.
        sig_probe = pose_translation_sigmas(out, spec, "probe")
        sig_tanker = pose_translation_sigmas(out, spec, "tanker")
        vec_var_diag = sig_probe ** 2 + sig_tanker ** 2
        rng = out[f"{spec.key}_vision_range"].to_numpy(dtype=float)
        unit = np.full_like(vision_vec, np.nan, dtype=float)
        good_rng = np.isfinite(rng) & (rng > 0.0)
        unit[good_rng] = vision_vec[good_rng] / rng[good_rng, None]
        range_var = np.sum((unit ** 2) * vec_var_diag, axis=1)
        range_sigma = np.sqrt(np.where(range_var >= 0.0, range_var, np.nan))
        range_sigma[~valid] = np.nan
        out[f"{spec.key}_range_sigma"] = range_sigma
        out[f"{spec.key}_range_3sigma"] = 3.0 * range_sigma

    return out


def add_truth_range(df: pd.DataFrame, truth_transform: np.ndarray | None) -> pd.DataFrame:
    out = df.copy()
    truth = numeric(out, ["base_to_rover_ecef_x", "base_to_rover_ecef_y", "base_to_rover_ecef_z"])
    if truth_transform is not None:
        truth = truth @ truth_transform.T
    for i, axis in enumerate("xyz"):
        out[f"truth_vector_{axis}"] = truth[:, i]
    out["truth_range"] = vector_norm(truth)
    out["truth_range_valid"] = np.isfinite(out["truth_range"].to_numpy(dtype=float))
    return out


def add_truth_range_errors(df: pd.DataFrame, specs: Sequence[PoseSpec]) -> pd.DataFrame:
    out = df.copy()
    truth_range = out["truth_range"].to_numpy(dtype=float)
    truth_valid = out["truth_range_valid"].to_numpy(dtype=bool)

    for spec in specs:
        method_range = out[f"{spec.key}_vision_range"].to_numpy(dtype=float)
        valid = out[f"{spec.key}_truth_compare_valid"].to_numpy(dtype=bool) & truth_valid & np.isfinite(method_range)
        err = method_range - truth_range
        out[f"{spec.key}_range_error"] = np.where(valid, err, np.nan)
        out[f"{spec.key}_abs_range_error"] = np.abs(out[f"{spec.key}_range_error"])
        sig = out[f"{spec.key}_range_sigma"].to_numpy(dtype=float)
        norm = np.full(len(out), np.nan, dtype=float)
        good = valid & np.isfinite(sig) & (sig > 0.0)
        norm[good] = err[good] / sig[good]
        out[f"{spec.key}_normalized_range_error"] = norm
        out[f"{spec.key}_inside_3sigma"] = good & (np.abs(norm) <= 3.0)
    return out


