def method_columns_with_suffix(m: MethodSpec, suffix: str) -> tuple[str, tuple[str, ...], tuple[str, ...]]:
    return (
        f"{m.valid_col}_{suffix}",
        tuple(f"{c}_{suffix}" for c in m.q_cols),
        tuple(f"{c}_{suffix}" for c in m.t_cols),
    )


def method_available_in_merged(df: pd.DataFrame, m: MethodSpec) -> bool:
    p_valid, p_q, p_t = method_columns_with_suffix(m, "probe")
    t_valid, t_q, t_t = method_columns_with_suffix(m, "tanker")
    return have_cols(df, [p_valid, *p_q, *p_t, t_valid, *t_q, *t_t])


def compute_vision_vectors(
    df: pd.DataFrame,
    methods: list[MethodSpec],
    receiver_probe_to_antenna: np.ndarray,
    tanker_center_to_antenna: np.ndarray,
) -> pd.DataFrame:
    out = df.copy()

    for m in methods:
        p_valid_col, p_q_cols, p_t_cols = method_columns_with_suffix(m, "probe")
        t_valid_col, t_q_cols, t_t_cols = method_columns_with_suffix(m, "tanker")

        valid = as_bool(out[p_valid_col]) & as_bool(out[t_valid_col])

        q_probe = numeric(out, p_q_cols)
        t_probe = numeric(out, p_t_cols)
        q_tanker = numeric(out, t_q_cols)
        t_tanker = numeric(out, t_t_cols)

        R_probe = quat_to_rotmat_batch(q_probe)
        R_tanker = quat_to_rotmat_batch(q_tanker)

        p_receiver_ant = t_probe + rotate_vectors_batch(R_probe, receiver_probe_to_antenna)
        p_tanker_ant = t_tanker + rotate_vectors_batch(R_tanker, tanker_center_to_antenna)
        vision_vec = p_tanker_ant - p_receiver_ant

        finite = finite_rows(p_receiver_ant) & finite_rows(p_tanker_ant) & finite_rows(vision_vec)
        valid &= finite

        for i, axis in enumerate("xyz"):
            out[f"{m.key}_receiver_ant_{axis}"] = p_receiver_ant[:, i]
            out[f"{m.key}_tanker_ant_{axis}"] = p_tanker_ant[:, i]
            out[f"{m.key}_vision_vec_{axis}"] = vision_vec[:, i]
        out[f"{m.key}_vision_range"] = vector_norm(vision_vec)
        out[f"{m.key}_truth_compare_valid"] = valid

    return out


def add_truth_vectors(
    df: pd.DataFrame,
    truth_transform: np.ndarray | None,
) -> pd.DataFrame:
    out = df.copy()
    truth = numeric(out, ["base_to_rover_ecef_x", "base_to_rover_ecef_y", "base_to_rover_ecef_z"])

    if truth_transform is not None:
        truth = truth @ truth_transform.T

    for i, axis in enumerate("xyz"):
        out[f"truth_raw_{axis}"] = numeric(out, ["base_to_rover_ecef_x", "base_to_rover_ecef_y", "base_to_rover_ecef_z"])[:, i]
        out[f"truth_cmp_base_to_rover_{axis}"] = truth[:, i]
    out["truth_cmp_base_to_rover_range"] = vector_norm(truth)
    return out


def choose_truth_sign(df: pd.DataFrame, methods: list[MethodSpec], truth_sign: str) -> tuple[int, pd.DataFrame]:
    rows = []
    truth = numeric(df, ["truth_cmp_base_to_rover_x", "truth_cmp_base_to_rover_y", "truth_cmp_base_to_rover_z"])

    for sign in (+1, -1):
        all_errs = []
        for m in methods:
            valid_col = f"{m.key}_truth_compare_valid"
            if valid_col not in df.columns:
                continue
            vision = numeric(df, [f"{m.key}_vision_vec_x", f"{m.key}_vision_vec_y", f"{m.key}_vision_vec_z"])
            valid = df[valid_col].fillna(False).to_numpy(dtype=bool) & finite_rows(vision) & finite_rows(truth)
            if np.any(valid):
                err_norm = vector_norm(vision[valid] - sign * truth[valid])
                all_errs.append(err_norm)
        if all_errs:
            arr = np.concatenate(all_errs)
            stats = finite_stats(arr)
        else:
            stats = finite_stats(np.array([], dtype=float))
        rows.append({"truth_sign": sign, **stats})

    diag = pd.DataFrame(rows)
    if truth_sign.lower() == "auto":
        usable = diag[np.isfinite(diag["median"])]
        if usable.empty:
            chosen = 1
        else:
            chosen = int(usable.sort_values("median").iloc[0]["truth_sign"])
    else:
        chosen = int(truth_sign)
        if chosen not in (-1, 1):
            raise ValueError("--truth-sign must be 'auto', '1', or '-1'.")

    return chosen, diag


def add_errors(df: pd.DataFrame, methods: list[MethodSpec], sign: int) -> pd.DataFrame:
    out = df.copy()
    truth = sign * numeric(out, ["truth_cmp_base_to_rover_x", "truth_cmp_base_to_rover_y", "truth_cmp_base_to_rover_z"])
    for i, axis in enumerate("xyz"):
        out[f"truth_{axis}"] = truth[:, i]
    out["truth_range"] = vector_norm(truth)

    for m in methods:
        vision = numeric(out, [f"{m.key}_vision_vec_x", f"{m.key}_vision_vec_y", f"{m.key}_vision_vec_z"])
        err = vision - truth
        valid = out[f"{m.key}_truth_compare_valid"].fillna(False).to_numpy(dtype=bool) & finite_rows(vision) & finite_rows(truth)

        for i, axis in enumerate("xyz"):
            out[f"{m.key}_err_{axis}"] = np.where(valid, err[:, i], np.nan)
        out[f"{m.key}_err_norm"] = np.where(valid, vector_norm(err), np.nan)
        out[f"{m.key}_range_error"] = np.where(valid, out[f"{m.key}_vision_range"].to_numpy(dtype=float) - out["truth_range"].to_numpy(dtype=float), np.nan)
    return out


def summarize_truth_errors(df: pd.DataFrame, methods: list[MethodSpec]) -> pd.DataFrame:
    rows = []
    for m in methods:
        valid = df.get(f"{m.key}_truth_compare_valid", pd.Series(False, index=df.index)).fillna(False).to_numpy(dtype=bool)
        row = {"method": m.label, "key": m.key, "valid_samples": int(np.sum(valid)), "total_samples": int(len(df))}
        for quantity, col in [
            ("x", f"{m.key}_err_x"),
            ("y", f"{m.key}_err_y"),
            ("z", f"{m.key}_err_z"),
            ("range", f"{m.key}_range_error"),
            ("vector_norm", f"{m.key}_err_norm"),
        ]:
            stats = finite_stats(df[col] if col in df.columns else np.array([]))
            for stat_name in ["mean", "median", "rmse", "mae", "p05", "p95", "max_abs"]:
                row[f"{quantity}_{stat_name}"] = stats[stat_name]
            row[f"{quantity}_count"] = stats["count"]
        rows.append(row)
    return pd.DataFrame(rows)


