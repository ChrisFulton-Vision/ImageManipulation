def build_summary_text(
    probe_csv: Path,
    tanker_csv: Path,
    novatel_txt: Path,
    df: pd.DataFrame,
    methods: list[MethodSpec],
    truth_sign: int,
    sign_diag: pd.DataFrame,
    err_summary: pd.DataFrame,
    sync_tolerance: float,
) -> str:
    lines: list[str] = []
    lines.append("TSPI/DGPS truth comparison")
    lines.append("==========================")
    lines.append("")
    lines.append(f"Probe CSV:   {probe_csv.name}")
    lines.append(f"Tanker CSV:  {tanker_csv.name}")
    lines.append(f"TSPI file:   {novatel_txt.name}")
    lines.append(f"Rows after synchronization attempt: {len(df)}")
    lines.append(f"Synchronization tolerance: {sync_tolerance:.6g} s")
    finite_truth = np.isfinite(df["gps_tow"].to_numpy(dtype=float)) if "gps_tow" in df.columns else np.zeros(len(df), dtype=bool)
    lines.append(f"Rows with matched TSPI truth: {int(np.sum(finite_truth))}")
    if "truth_time_error_s" in df.columns:
        dt = df["truth_time_error_s"].to_numpy(dtype=float)
        dt = dt[np.isfinite(dt)]
        if dt.size:
            lines.append(f"Truth sync residual: median={np.median(dt):.6g} s, max_abs={np.max(np.abs(dt)):.6g} s")
    lines.append("")

    lines.append("Truth sign diagnostic")
    lines.append("---------------------")
    lines.append(f"Chosen truth sign: {truth_sign}")
    for _, row in sign_diag.iterrows():
        lines.append(
            f"sign {int(row['truth_sign']):+d}: median vector error={row['median']:.6g}, "
            f"RMSE={row['rmse']:.6g}, count={int(row['count'])}"
        )
    lines.append("")

    lines.append("Method truth-error summary")
    lines.append("--------------------------")
    for _, row in err_summary.iterrows():
        lines.append(
            f"{row['method']}: samples={int(row['valid_samples'])}/{int(row['total_samples'])}, "
            f"vector RMSE={row['vector_norm_rmse']:.6g}, "
            f"median vector norm={row['vector_norm_median']:.6g}, "
            f"range RMSE={row['range_rmse']:.6g}, "
            f"x/y/z RMSE=({row['x_rmse']:.6g}, {row['y_rmse']:.6g}, {row['z_rmse']:.6g})"
        )
    lines.append("")

    best = err_summary[np.isfinite(err_summary["vector_norm_rmse"])].sort_values("vector_norm_rmse")
    if not best.empty:
        lines.append(f"Lowest 3D vector-error RMSE: {best.iloc[0]['method']}")
    lines.append("")
    lines.append("Coordinate note")
    lines.append("---------------")
    lines.append(
        "This first-pass comparison assumes the TSPI vector, after optional sign and optional "
        "--truth-transform, is expressed in the same component convention as the vision-derived "
        "antenna-to-antenna vector. If component errors show a clear axis permutation/sign pattern, "
        "rerun with --truth-transform."
    )
    return "\n".join(lines)


