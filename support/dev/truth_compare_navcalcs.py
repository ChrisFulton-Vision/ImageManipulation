def tint_color(color: str, amount: float) -> str:
    rgb = np.array(mcolors.to_rgb(color), dtype=float)
    amount = float(np.clip(amount, -1.0, 1.0))
    if amount >= 0.0:
        mixed = rgb + (1.0 - rgb) * amount
    else:
        mixed = rgb * (1.0 + amount)
    return mcolors.to_hex(np.clip(mixed, 0.0, 1.0))


def method_style(spec: PoseSpec) -> dict[str, object]:
    base = BASE_METHOD_COLORS.get(spec.base_key, "#4c4c4c")
    color = tint_color(base, FAMILY_SHADE_OFFSETS.get(spec.family, 0.0))
    return {
        "color": color,
        "linestyle": FAMILY_LINESTYLES.get(spec.family, "-"),
    }


def method_marker(spec: PoseSpec) -> str:
    return FAMILY_MARKERS.get(spec.family, "o")


def pair_style(a: PoseSpec, b: PoseSpec) -> dict[str, object]:
    color_a = np.array(mcolors.to_rgb(method_style(a)["color"]), dtype=float)
    color_b = np.array(mcolors.to_rgb(method_style(b)["color"]), dtype=float)
    mixed = mcolors.to_hex(np.clip(0.5 * (color_a + color_b), 0.0, 1.0))
    linestyle = "--" if a.family != b.family else "-"
    return {"color": mixed, "linestyle": linestyle}


