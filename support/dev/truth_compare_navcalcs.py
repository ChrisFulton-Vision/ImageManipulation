def savefig(path: Path) -> None:
    plt.tight_layout()
    plt.savefig(path, dpi=220)
    plt.close()


def plot_tracking(df: pd.DataFrame, methods: list[MethodSpec], out_dir: Path) -> None:
    x, xlabel = get_plot_time_axis(df)
    for axis in "xyz":
        plt.figure(figsize=(10, 5))
        plt.plot(x, df[f"truth_{axis}"], linewidth=2.0, label="TSPI/DGPS truth")
        for m in methods:
            col = f"{m.key}_vision_vec_{axis}"
            if col in df.columns:
                y = df[col].where(df[f"{m.key}_truth_compare_valid"], np.nan)
                plt.plot(x, y, linewidth=1.0, label=m.label)
        plt.xlabel(xlabel)
        plt.ylabel(f"{axis.upper()} component")
        plt.title(f"Antenna-to-antenna vector tracking: {axis.upper()}")
        plt.legend(fontsize="small")
        savefig(out_dir / f"tracking_{axis}.png")

    plt.figure(figsize=(10, 5))
    plt.plot(x, df["truth_range"], linewidth=2.0, label="TSPI/DGPS truth")
    for m in methods:
        col = f"{m.key}_vision_range"
        if col in df.columns:
            y = df[col].where(df[f"{m.key}_truth_compare_valid"], np.nan)
            plt.plot(x, y, linewidth=1.0, label=m.label)
    plt.xlabel(xlabel)
    plt.ylabel("Vector magnitude / range")
    plt.title("Antenna-to-antenna range tracking")
    plt.legend(fontsize="small")
    savefig(out_dir / "tracking_range.png")


def plot_errors(df: pd.DataFrame, methods: list[MethodSpec], out_dir: Path) -> None:
    x, xlabel = get_plot_time_axis(df)
    for quantity, ylabel, title, fname in [
        ("err_x", "X error", "Truth error: X component", "error_x.png"),
        ("err_y", "Y error", "Truth error: Y component", "error_y.png"),
        ("err_z", "Z error", "Truth error: Z component", "error_z.png"),
        ("range_error", "Range error", "Truth error: vector magnitude", "error_range.png"),
        ("err_norm", "3D error norm", "Truth error: 3D vector norm", "error_norm.png"),
    ]:
        plt.figure(figsize=(10, 5))
        for m in methods:
            col = f"{m.key}_{quantity}"
            if col in df.columns:
                plt.plot(x, df[col], linewidth=1.0, label=m.label)
        plt.xlabel(xlabel)
        plt.ylabel(ylabel)
        plt.title(title)
        plt.axhline(0.0, linewidth=0.8)
        plt.legend(fontsize="small")
        savefig(out_dir / fname)


