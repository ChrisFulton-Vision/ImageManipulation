def comparison_class(a: PoseSpec, b: PoseSpec) -> str:
    if a.base_key == b.base_key and {a.family, b.family} == {"raw", "fg"}:
        return "raw_vs_own_fg"
    if a.family == "fg" and b.family == "fg":
        return "fg_vs_fg"
    if a.family == "raw" and b.family == "raw":
        return "raw_vs_raw"
    return "raw_vs_other_fg"


def pose_pair_key(a: PoseSpec, b: PoseSpec, suffix: str) -> str:
    return f"{suffix}_{a.key}__minus__{b.key}"


def add_pairwise_pose_differences(df: pd.DataFrame, specs: Sequence[PoseSpec]) -> pd.DataFrame:
    out = df.copy()
    extra: dict[str, np.ndarray] = {}
    for suffix in ("probe", "tanker"):
        for a, b in itertools.combinations(specs, 2):
            q_a, t_a, valid_a = pose_arrays(out, a, suffix)
            q_b, t_b, valid_b = pose_arrays(out, b, suffix)
            valid = valid_a & valid_b & finite_rows(q_a) & finite_rows(q_b) & finite_rows(t_a) & finite_rows(t_b)
            pk = pose_pair_key(a, b, suffix)
            trans_delta = t_a - t_b
            angle_delta = quat_angle_deg_batch(q_a, q_b)
            extra[f"posepair_{pk}_translation_delta_norm"] = np.where(valid, vector_norm(trans_delta), np.nan)
            extra[f"posepair_{pk}_attitude_delta_deg"] = np.where(valid, angle_delta, np.nan)
            for i, axis in enumerate("xyz"):
                extra[f"posepair_{pk}_translation_delta_{axis}"] = np.where(valid, trans_delta[:, i], np.nan)
    if extra:
        out = pd.concat([out, pd.DataFrame(extra, index=out.index)], axis=1).copy()
    return out

