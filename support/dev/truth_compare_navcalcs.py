def pair_key(a: PoseSpec, b: PoseSpec) -> str:
    return f"{a.key}__minus__{b.key}"


def pair_label(a: PoseSpec, b: PoseSpec) -> str:
    return f"{a.label} - {b.label}"


def add_pairwise_vector_differences(df: pd.DataFrame, specs: Sequence[PoseSpec]) -> pd.DataFrame:
    out = df.copy()
    extra: dict[str, np.ndarray] = {}
    for a, b in itertools.combinations(specs, 2):
        pk = pair_key(a, b)
        va = numeric(out, [f"{a.key}_vision_vec_x", f"{a.key}_vision_vec_y", f"{a.key}_vision_vec_z"])
        vb = numeric(out, [f"{b.key}_vision_vec_x", f"{b.key}_vision_vec_y", f"{b.key}_vision_vec_z"])
        valid = (
            out[f"{a.key}_truth_compare_valid"].to_numpy(dtype=bool)
            & out[f"{b.key}_truth_compare_valid"].to_numpy(dtype=bool)
            & finite_rows(va)
            & finite_rows(vb)
        )
        delta = va - vb
        for i, axis in enumerate("xyz"):
            extra[f"pair_{pk}_vec_delta_{axis}"] = np.where(valid, delta[:, i], np.nan)
        extra[f"pair_{pk}_vector_delta_norm"] = np.where(valid, vector_norm(delta), np.nan)
        range_delta = out[f"{a.key}_vision_range"].to_numpy(dtype=float) - out[f"{b.key}_vision_range"].to_numpy(dtype=float)
        extra[f"pair_{pk}_range_delta"] = np.where(valid, range_delta, np.nan)
        extra[f"pair_{pk}_abs_range_delta"] = np.abs(extra[f"pair_{pk}_range_delta"])
    if extra:
        out = pd.concat([out, pd.DataFrame(extra, index=out.index)], axis=1).copy()
    return out

