"""
Compare probe/tanker navcalcs pose estimates against NovAtel / TSPI truth,
including SE(3) factor-graph smoothed pose outputs.

This is the range-safe comparison script.

Why range-safe?
----------------
The NovAtel / TSPI truth file gives a relative vector in its own coordinate
convention. For the current flight-analysis use case, the TSPI vector magnitude
is valid, but its x/y/z components are not directly comparable with the camera /
pose-estimator axes. Therefore, this script compares all pose methods to truth
using only vector magnitude / range.

Full x/y/z vector comparisons are still produced between vision-derived methods,
because those quantities live in the same internal pose-estimator convention after
probe/tanker synchronization.

Inputs
------
1. Probe / receiver navcalcs CSV generated by the pose pipeline.
2. Tanker / target navcalcs CSV generated by the pose pipeline.
3. Whitespace-delimited NovAtel / TSPI text file containing relative base-to-rover
   ECEF vector columns.

Outputs
-------
The output directory contains:

  plots/
    - truth range overlays and range-error plots
    - raw method vs its own SE(3) factor graph plots
    - all FG vs all FG plots
    - pairwise method comparison plots
    - sigma / 3-sigma range-error plots when covariance information exists
    - scatter, histogram, and smoothness plots
    - each plot written as both PNG and vector PDF

  tables/
    - merged_truth_comparison.csv
    - truth_range_error_summary.csv
    - pairwise_vector_summary.csv
    - pairwise_pose_summary.csv
    - raw_vs_own_fg_summary.csv
    - smoothness_summary.csv
    - method_availability_summary.csv

Example
-------
python truth_compare_navcalcs.py \
    --probe-csv navcalcs_PROBE_BothContext_01062024_0_3M.csv \
    --tanker-csv navcalcs_GIII_Pseudo.csv \
    --novatel-txt relative_tspi.txt \
    --out truth_compare_probe_tanker_fg

Notes
-----
- image_time in navcalcs is converted to GPS seconds when it appears to be Unix
  epoch time. This preserves the previous script's sync behavior.
- Truth x/y/z component plots are intentionally not generated by default.
- Lever arms are applied before forming the antenna-to-antenna vision vector.
"""

