def quat_to_rotmat_batch(q: np.ndarray) -> np.ndarray:
    """Return R(q) for scalar-first quaternions, row-wise.

    The returned rotation maps object-frame vectors into the camera / estimator
    frame under the convention used by the navcalcs pose output.
    """
    q = q.astype(float)
    n = np.linalg.norm(q, axis=1, keepdims=True)
    n[n == 0.0] = np.nan
    q = q / n

    w, x, y, z = q[:, 0], q[:, 1], q[:, 2], q[:, 3]
    R = np.empty((len(q), 3, 3), dtype=float)

    R[:, 0, 0] = 1.0 - 2.0 * (y * y + z * z)
    R[:, 0, 1] = 2.0 * (x * y - z * w)
    R[:, 0, 2] = 2.0 * (x * z + y * w)

    R[:, 1, 0] = 2.0 * (x * y + z * w)
    R[:, 1, 1] = 1.0 - 2.0 * (x * x + z * z)
    R[:, 1, 2] = 2.0 * (y * z - x * w)

    R[:, 2, 0] = 2.0 * (x * z - y * w)
    R[:, 2, 1] = 2.0 * (y * z + x * w)
    R[:, 2, 2] = 1.0 - 2.0 * (x * x + y * y)
    return R


def rotate_vectors_batch(R: np.ndarray, v: np.ndarray) -> np.ndarray:
    return np.einsum("nij,j->ni", R, v)


def quat_angle_deg_batch(q_a: np.ndarray, q_b: np.ndarray) -> np.ndarray:
    """Shortest angular separation between scalar-first unit quaternions."""
    q_a = q_a.astype(float)
    q_b = q_b.astype(float)
    na = np.linalg.norm(q_a, axis=1)
    nb = np.linalg.norm(q_b, axis=1)
    denom = na * nb
    dot = np.sum(q_a * q_b, axis=1)
    out = np.full(len(q_a), np.nan, dtype=float)
    good = np.isfinite(dot) & np.isfinite(denom) & (denom > 0.0)
    d = np.clip(np.abs(dot[good] / denom[good]), -1.0, 1.0)
    out[good] = np.rad2deg(2.0 * np.arccos(d))
    return out


