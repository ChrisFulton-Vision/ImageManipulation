def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def have_cols(df: pd.DataFrame, cols: Iterable[str]) -> bool:
    return all(c in df.columns for c in cols)


def as_bool(series: pd.Series) -> np.ndarray:
    if series.dtype == bool:
        return series.fillna(False).to_numpy(dtype=bool)
    if pd.api.types.is_numeric_dtype(series):
        return (series.fillna(0).astype(float) != 0.0).to_numpy(dtype=bool)
    true_values = {"true", "t", "1", "yes", "y", "valid"}
    return series.fillna("false").astype(str).str.strip().str.lower().isin(true_values).to_numpy(dtype=bool)


def numeric(df: pd.DataFrame, cols: Iterable[str]) -> np.ndarray:
    return df.loc[:, list(cols)].apply(pd.to_numeric, errors="coerce").to_numpy(dtype=float)


def finite_rows(arr: np.ndarray) -> np.ndarray:
    return np.all(np.isfinite(arr), axis=1)


def vector_norm(arr: np.ndarray) -> np.ndarray:
    return np.linalg.norm(arr, axis=1)


def finite_stats(values: np.ndarray | pd.Series) -> dict[str, float | int]:
    arr = np.asarray(values, dtype=float)
    arr = arr[np.isfinite(arr)]
    if arr.size == 0:
        return {
            "count": 0,
            "mean": np.nan,
            "median": np.nan,
            "rmse": np.nan,
            "mae": np.nan,
            "p05": np.nan,
            "p95": np.nan,
            "max_abs": np.nan,
        }
    return {
        "count": int(arr.size),
        "mean": float(np.mean(arr)),
        "median": float(np.median(arr)),
        "rmse": float(np.sqrt(np.mean(arr ** 2))),
        "mae": float(np.mean(np.abs(arr))),
        "p05": float(np.percentile(arr, 5)),
        "p95": float(np.percentile(arr, 95)),
        "max_abs": float(np.max(np.abs(arr))),
    }


def write_markdown_table(df: pd.DataFrame, path: Path, float_fmt: str = ".5g") -> None:
    def fmt(x: object) -> str:
        if isinstance(x, (float, np.floating)):
            if math.isnan(float(x)):
                return ""
            return format(float(x), float_fmt)
        return str(x)

    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "| " + " | ".join(["---"] * len(cols)) + " |"]
    for _, row in df.iterrows():
        lines.append("| " + " | ".join(fmt(row[c]) for c in cols) + " |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def get_plot_time_axis(df: pd.DataFrame) -> tuple[np.ndarray, str]:
    """Return the best available x-axis series and label for plots."""
    for col, label in [
        ("image_time", "Image time (s)"),
        ("image_time_probe", "Probe image time (s)"),
        ("sync_time_s", "GPS-aligned sync time (s)"),
    ]:
        if col in df.columns:
            return df[col].to_numpy(dtype=float), label
    raise KeyError("No usable plot time column found. Expected one of: image_time, image_time_probe, sync_time_s.")


def unix_to_gps_seconds(unix_seconds: np.ndarray) -> np.ndarray:
    """Convert Unix UTC seconds to GPS seconds on the continuous GPS timescale."""
    return np.asarray(unix_seconds, dtype=float) - UNIX_TO_GPS_EPOCH_SECONDS + GPS_MINUS_UTC_LEAP_SECONDS


def prepare_navcalcs_sync_time(df: pd.DataFrame) -> pd.DataFrame:
    """Add sync columns derived from image_time.

    Navcalcs files typically store image_time as Unix epoch seconds. TSPI files
    provide GPS week and time-of-week, so synchronization must happen on a
    common timescale.
    """
    out = df.copy()
    image_time = out["image_time"].to_numpy(dtype=float)

    # Large values are treated as Unix epoch seconds; smaller values are assumed
    # to already be in a GPS-relative scale compatible with the TSPI file.
    if np.nanmedian(image_time) > 1.0e9:
        sync_time = unix_to_gps_seconds(image_time)
    else:
        sync_time = image_time

    out["sync_time_s"] = sync_time
    out["sync_gps_week"] = np.floor(sync_time / GPS_WEEK_SECONDS)
    out["sync_gps_tow"] = sync_time - out["sync_gps_week"] * GPS_WEEK_SECONDS
    return out


# -----------------------------------------------------------------------------
# Quaternion / rotation helpers
# -----------------------------------------------------------------------------

def quat_to_rotmat_batch(q: np.ndarray) -> np.ndarray:
    """Return R(q) for scalar-first quaternions, row-wise.

    The returned rotation maps object-frame vectors into the camera/estimator frame
    under the convention used by the navcalcs pose output.
    """
    q = q.astype(float)
    n = np.linalg.norm(q, axis=1, keepdims=True)
    n[n == 0.0] = np.nan
    q = q / n

    w, x, y, z = q[:, 0], q[:, 1], q[:, 2], q[:, 3]
    R = np.empty((len(q), 3, 3), dtype=float)

    R[:, 0, 0] = 1.0 - 2.0 * (y * y + z * z)
    R[:, 0, 1] = 2.0 * (x * y - z * w)
    R[:, 0, 2] = 2.0 * (x * z + y * w)

    R[:, 1, 0] = 2.0 * (x * y + z * w)
    R[:, 1, 1] = 1.0 - 2.0 * (x * x + z * z)
    R[:, 1, 2] = 2.0 * (y * z - x * w)

    R[:, 2, 0] = 2.0 * (x * z - y * w)
    R[:, 2, 1] = 2.0 * (y * z + x * w)
    R[:, 2, 2] = 1.0 - 2.0 * (x * x + y * y)
    return R


def rotate_vectors_batch(R: np.ndarray, v: np.ndarray) -> np.ndarray:
    """Compute R_i @ v for all rows."""
    return np.einsum("nij,j->ni", R, v)


