def build_summary_text(
    probe_csv: Path,
    tanker_csv: Path,
    novatel_txt: Path,
    df: pd.DataFrame,
    specs: Sequence[PoseSpec],
    sync_tolerance: float,
    truth_summary: pd.DataFrame,
    vector_summary: pd.DataFrame,
    pose_summary: pd.DataFrame,
    smoothness_summary: pd.DataFrame,
) -> str:
    lines: list[str] = []
    lines.append("Navcalcs + SE(3) factor-graph truth-range comparison")
    lines.append("======================================================")
    lines.append("")
    lines.append(f"Probe CSV:   {probe_csv.name}")
    lines.append(f"Tanker CSV:  {tanker_csv.name}")
    lines.append(f"TSPI file:   {novatel_txt.name}")
    lines.append(f"Rows after synchronization attempt: {len(df)}")
    lines.append(f"Synchronization tolerance: {sync_tolerance:.6g} s")
    finite_truth = df["truth_range_valid"].to_numpy(dtype=bool) if "truth_range_valid" in df.columns else np.zeros(len(df), dtype=bool)
    lines.append(f"Rows with matched truth magnitude: {int(np.sum(finite_truth))}")
    for label, col in [("Tanker", "tanker_time_error_s"), ("Truth", "truth_time_error_s")]:
        if col in df.columns:
            dt = df[col].to_numpy(dtype=float)
            dt = dt[np.isfinite(dt)]
            if dt.size:
                lines.append(f"{label} sync residual: median={np.median(dt):.6g} s, max_abs={np.max(np.abs(dt)):.6g} s")
    lines.append("")

    lines.append("Available pose/vector methods")
    lines.append("-----------------------------")
    for spec in specs:
        valid = df[f"{spec.key}_truth_compare_valid"].to_numpy(dtype=bool)
        truth_valid = valid & finite_truth
        sigma_valid = np.isfinite(df[f"{spec.key}_range_sigma"].to_numpy(dtype=float))
        lines.append(
            f"{spec.label}: vector samples={int(np.sum(valid))}, "
            f"truth-range samples={int(np.sum(truth_valid))}, "
            f"range-sigma samples={int(np.sum(sigma_valid))}"
        )
    lines.append("")

    lines.append("Best truth-range agreement")
    lines.append("--------------------------")
    usable = truth_summary[np.isfinite(pd.to_numeric(truth_summary["range_error_rmse"], errors="coerce"))].copy()
    if usable.empty:
        lines.append("No method had finite truth-range error statistics.")
    else:
        usable = usable.sort_values("range_error_rmse")
        for _, row in usable.head(5).iterrows():
            lines.append(
                f"{row['method']}: RMSE={row['range_error_rmse']:.6g}, "
                f"median abs={row['abs_range_error_median']:.6g}, "
                f"p95 abs={row['abs_range_error_p95']:.6g}, "
                f"samples={int(row['valid_samples'])}"
            )
    lines.append("")

    lines.append("Raw vs own FG highlights")
    lines.append("------------------------")
    own = vector_summary[vector_summary["comparison_class"] == "raw_vs_own_fg"].copy()
    if own.empty:
        lines.append("No raw/own-FG pairs were available.")
    else:
        for _, row in own.iterrows():
            lines.append(
                f"{row['pair']}: range-delta RMSE={row['range_delta_rmse']:.6g}, "
                f"median vector delta={row['vector_delta_norm_median']:.6g}, "
                f"p95 vector delta={row['vector_delta_norm_p95']:.6g}"
            )
    lines.append("")

    lines.append("FG-to-FG highlights")
    lines.append("-------------------")
    fg = vector_summary[vector_summary["comparison_class"] == "fg_vs_fg"].copy()
    if fg.empty:
        lines.append("No FG/FG pairs were available.")
    else:
        fg = fg.sort_values("vector_delta_norm_median")
        for _, row in fg.head(6).iterrows():
            lines.append(
                f"{row['pair']}: median vector delta={row['vector_delta_norm_median']:.6g}, "
                f"p95={row['vector_delta_norm_p95']:.6g}, "
                f"range-delta RMSE={row['range_delta_rmse']:.6g}"
            )
    lines.append("")

    lines.append("Smoothness highlights")
    lines.append("---------------------")
    smooth = smoothness_summary[np.isfinite(pd.to_numeric(smoothness_summary["vector_rate_norm_median"], errors="coerce"))].copy()
    if smooth.empty:
        lines.append("No finite smoothness statistics were available.")
    else:
        smooth = smooth.sort_values("vector_rate_norm_median")
        for _, row in smooth.head(5).iterrows():
            lines.append(
                f"{row['method']}: median vector-rate norm={row['vector_rate_norm_median']:.6g}, "
                f"p95 vector-rate norm={row['vector_rate_norm_p95']:.6g}, "
                f"median abs range-rate={row['abs_range_rate_median']:.6g}"
            )
    lines.append("")

    lines.append("Coordinate note")
    lines.append("---------------")
    lines.append(
        "Truth comparisons are range-only by design. The TSPI x/y/z vector components are "
        "stored in the merged table for auditing, but the default plots and statistics do "
        "not treat those components as directionally comparable to camera-frame pose outputs. "
        "Method-to-method comparisons do use x/y/z vector deltas because those vectors are "
        "computed inside the shared vision/navigation convention."
    )
    return "\n".join(lines)


