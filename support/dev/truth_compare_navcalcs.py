"""
Compare vision navcalcs pose estimates against TSPI / NovAtel DGPS truth.

This script takes three files:

  1. A probe/receiver navcalcs CSV generated by the pose pipeline.
  2. A tanker/target navcalcs CSV generated by the pose pipeline.
  3. A whitespace-delimited NovAtel / TSPI text file containing the relative
     base-to-rover ECEF vector.

For each pose method, the script:

  * synchronizes probe, tanker, and TSPI rows using image_time / GPS time-of-week;
  * applies lever-arm corrections from object origins to NovAtel antenna locations;
  * subtracts receiver antenna from tanker antenna to form a vision-estimated
    antenna-to-antenna vector;
  * compares that vector with the TSPI base-to-rover vector, with automatic sign
    selection available;
  * generates x/y/z/range tracking plots, x/y/z/range error plots, vector-error
    norm plots, and summary CSV/Markdown tables.

Default lever arms are the values supplied during dissertation analysis:

    receiver probe-tip to receiver antenna, receiver frame:
        [-9.27027, 0.45487, 0.67881]

    tanker geometric center to tanker antenna, tanker frame:
        [7.78935, -0.00469, -0.06247]

Important coordinate note:
    By default, the script compares the TSPI vector directly to the vision vector
    after the optional sign flip. If the TSPI ECEF axes must be rotated into the
    receiver-camera/processing frame, provide --truth-transform with nine row-major
    matrix entries.

Example:
    python truth_compare_navcalcs.py \
        --probe-csv navcalcs_PROBE_BothContext_01062024_0_3M.csv \
        --tanker-csv navcalcs_GIII_Pseudo.csv \
        --novatel-txt relative_tspi.txt \
        --out truth_compare_probe_tanker

Optional fixed sign convention:
    python truth_compare_navcalcs.py ... --truth-sign -1

Optional truth-frame transform, row-major 3x3:
    python truth_compare_navcalcs.py ... --truth-transform 1 0 0 0 1 0 0 0 1
"""

