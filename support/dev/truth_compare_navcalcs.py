def plot_smoothness(df: pd.DataFrame, specs: Sequence[PoseSpec], out_dir: Path) -> None:
    x, xlabel = elapsed_time_axis(df)
    for family, filename, title_suffix in [
        (None, "smoothness_range_rate_all_methods.png", "all methods"),
        ("raw", "smoothness_range_rate_raw_methods.png", "raw methods"),
        ("fg", "smoothness_range_rate_fg_methods.png", "SE(3) factor graphs"),
    ]:
        subset = plot_specs_for_family(specs, family)
        if not subset:
            continue
        plt.figure(figsize=(12, 6))
        ax = plt.gca()
        for spec in subset:
            y = df[f"{spec.key}_vision_range"].where(df[f"{spec.key}_truth_compare_valid"], np.nan).to_numpy(dtype=float)
            dy = np.full(len(df), np.nan, dtype=float)
            valid = np.isfinite(y) & np.isfinite(x)
            idx = np.where(valid)[0]
            if idx.size >= 2:
                dt = np.diff(x[idx])
                dr = np.diff(y[idx])
                good = np.isfinite(dt) & (dt > 0.0)
                rates = np.full_like(dr, np.nan, dtype=float)
                rates[good] = dr[good] / dt[good]
                dy[idx[1:]] = rates
            plt.plot(x, dy, linewidth=1.5, label=spec.label, **method_style(spec))
        plt.axhline(0.0, linewidth=0.9, color=REFERENCE_COLOR)
        plt.xlabel(xlabel)
        plt.ylabel("Range rate from synchronized samples")
        plt.title(f"Range-rate smoothness diagnostic: {title_suffix}")
        style_axes(ax)
        plt.legend()
        savefig(out_dir / filename)


def plot_native_fg_range_check(df: pd.DataFrame, specs: Sequence[PoseSpec], out_dir: Path) -> None:
    """Compare native per-object FG range column to ||tvec|| when available.

    This is a sanity plot for the FG columns themselves. It does not compare to
    truth and does not include lever-arm antenna reconstruction.
    """
    x, xlabel = elapsed_time_axis(df)
    for spec in specs:
        if spec.native_range_col is None:
            continue
        for suffix in ("probe", "tanker"):
            native_col = suffixed(spec.native_range_col, suffix)
            if native_col not in df.columns:
                continue
            _, _, pose_t_cols = spec_cols(spec, suffix)
            t = numeric(df, pose_t_cols)
            t_norm = vector_norm(t)
            native = numeric_series(df, native_col)
            diff = native - t_norm
            if not np.any(np.isfinite(diff)):
                continue
            plt.figure(figsize=(12, 5))
            ax = plt.gca()
            plt.plot(x, diff, linewidth=1.5, label="native FG range - ||tvec||", **method_style(spec))
            plt.axhline(0.0, linewidth=0.9, color=REFERENCE_COLOR)
            plt.xlabel(xlabel)
            plt.ylabel("Range consistency delta")
            plt.title(f"Native FG range consistency: {spec.label}, {suffix}")
