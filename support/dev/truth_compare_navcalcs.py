def parse_cov6_translation_sigmas_cell(cell: object) -> np.ndarray:
    """Return sqrt of the first 3 diagonal entries from a serialized 6x6 covariance."""
    if cell is None or (isinstance(cell, float) and math.isnan(cell)):
        return np.array([np.nan, np.nan, np.nan], dtype=float)
    text = str(cell).strip()
    if not text:
        return np.array([np.nan, np.nan, np.nan], dtype=float)
    try:
        arr = np.fromstring(text.replace(";", ","), sep=",")
        if arr.size == 36:
            M = arr.reshape(6, 6)
            diag = np.diag(M)[:3]
        elif arr.size >= 6:
            # Some pipelines serialize only diagonal covariance terms.
            diag = arr[:3]
        else:
            return np.array([np.nan, np.nan, np.nan], dtype=float)
        diag = np.where(diag >= 0.0, diag, np.nan)
        return np.sqrt(diag)
    except Exception:
        return np.array([np.nan, np.nan, np.nan], dtype=float)


def pose_translation_sigmas(df: pd.DataFrame, spec: PoseSpec, suffix: str) -> np.ndarray:
    """Return per-row translational sigma for one pose/object if available.

    Preference order matters.  Raw QnP-family poses may have both the original
    local solver covariance, e.g. qnp_cov6, and the truth-diagnostic effective
    covariance written by the SE(3) smoother, e.g. qnp_cov6_effective.  For
    truth-range coverage plots, use the effective raw covariance first when it
    exists; otherwise fall back to the original covariance so older CSVs still
    plot.
    """

    # Fast path: explicit sigma columns.  FG poses already have these.  Raw
    # poses get *_sigma_x_effective columns when the smoother appends raw
    # effective covariance diagnostics.
    sigma_candidates: list[tuple[str, str, str]] = []
    if spec.family == "raw":
        sigma_candidates.append(
            (
                f"{spec.base_key}_sigma_x_effective",
                f"{spec.base_key}_sigma_y_effective",
                f"{spec.base_key}_sigma_z_effective",
            )
        )
    if spec.sigma_t_cols is not None:
        sigma_candidates.append(spec.sigma_t_cols)

    for cols in sigma_candidates:
        sigma_cols = tuple(suffixed(c, suffix) for c in cols)
        if have_cols(df, sigma_cols):
            sig = numeric(df, sigma_cols)
            if np.any(np.isfinite(sig)):
                return sig

    # Slower path: parse covariance strings.  Prefer raw *_cov6_effective over
    # raw *_cov6; the latter is the local Hessian/solver covariance and is often
    # intentionally overconfident for truth-level coverage.
    cov_candidates: list[str] = []
    if spec.family == "raw":
        cov_candidates.append(f"{spec.base_key}_cov6_effective")
    if spec.cov6_col is not None:
        cov_candidates.append(spec.cov6_col)

    for cov_base_col in cov_candidates:
        cov_col = suffixed(cov_base_col, suffix)
        if cov_col in df.columns:
            vals = [parse_cov6_translation_sigmas_cell(v) for v in df[cov_col].to_numpy()]
            sig = np.vstack(vals) if vals else np.full((len(df), 3), np.nan)
            if np.any(np.isfinite(sig)):
                return sig

    return np.full((len(df), 3), np.nan, dtype=float)


