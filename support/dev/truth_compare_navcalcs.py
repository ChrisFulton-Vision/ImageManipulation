def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Compare probe/tanker navcalcs pose estimates against TSPI/DGPS truth.")
    parser.add_argument("--probe-csv", type=Path, help="Probe/receiver navcalcs CSV.")
    parser.add_argument("--tanker-csv", type=Path, help="Tanker/target navcalcs CSV.")
    parser.add_argument("--novatel-txt", type=Path, help="Whitespace-delimited NovAtel/TSPI relative-vector text file.")
    parser.add_argument("--out", type=Path, default=None, help="Output directory. Defaults to truth_compare_<probe>_<tanker>.")
    parser.add_argument("--sync-tolerance", type=float, default=0.075, help="Nearest-time synchronization tolerance in seconds. Default: 0.075.")
    parser.add_argument("--truth-sign", default="auto", choices=["auto", "1", "-1"], help="Sign applied to TSPI vector before comparison. Default: auto.")
    parser.add_argument(
        "--truth-transform",
        type=float,
        nargs=9,
        default=None,
        metavar=("r11", "r12", "r13", "r21", "r22", "r23", "r31", "r32", "r33"),
        help="Optional row-major 3x3 transform applied to TSPI vector before sign selection.",
    )
    parser.add_argument(
        "--receiver-probe-to-antenna",
        type=float,
        nargs=3,
        default=DEFAULT_RECEIVER_PROBE_TO_ANTENNA.tolist(),
        metavar=("X", "Y", "Z"),
        help="Receiver probe-tip to receiver antenna lever arm in receiver/probe frame.",
    )
    parser.add_argument(
        "--tanker-center-to-antenna",
        type=float,
        nargs=3,
        default=DEFAULT_TANKER_CENTER_TO_ANTENNA.tolist(),
        metavar=("X", "Y", "Z"),
        help="Tanker geometric center to tanker antenna lever arm in tanker frame.",
    )
    parser.add_argument("--no-dialog", action="store_true", help="Disable file dialogs when required paths are omitted.")
    return parser.parse_args()


def maybe_dialog_paths(args: argparse.Namespace) -> argparse.Namespace:
    if args.no_dialog or (args.probe_csv and args.tanker_csv and args.novatel_txt):
        return args
    try:
        from tkinter import Tk, filedialog
        root = Tk()
        root.withdraw()
        if args.probe_csv is None:
            args.probe_csv = Path(filedialog.askopenfilename(title="Select probe/receiver navcalcs CSV", filetypes=[("CSV", "*.csv"), ("All files", "*.*")]))
        if args.tanker_csv is None:
            args.tanker_csv = Path(filedialog.askopenfilename(title="Select tanker/target navcalcs CSV", filetypes=[("CSV", "*.csv"), ("All files", "*.*")]))
        if args.novatel_txt is None:
            args.novatel_txt = Path(filedialog.askopenfilename(title="Select NovAtel / TSPI text file", filetypes=[("Text", "*.txt *.dat *.csv"), ("All files", "*.*")]))
        root.destroy()
    except Exception:
        return args
    return args


def main() -> None:
    args = maybe_dialog_paths(parse_args())
    if args.probe_csv is None or args.tanker_csv is None or args.novatel_txt is None:
        raise SystemExit("Provide --probe-csv, --tanker-csv, and --novatel-txt, or run without --no-dialog.")

    probe_csv = Path(args.probe_csv)
    tanker_csv = Path(args.tanker_csv)
    novatel_txt = Path(args.novatel_txt)
    out = args.out or Path(f"truth_compare_{probe_csv.stem}_{tanker_csv.stem}")
    plots_dir = out / "plots"
    tables_dir = out / "tables"
    ensure_dir(out)
    ensure_dir(plots_dir)
    ensure_dir(tables_dir)

    receiver_probe_to_antenna = np.asarray(args.receiver_probe_to_antenna, dtype=float)
    tanker_center_to_antenna = np.asarray(args.tanker_center_to_antenna, dtype=float)
    truth_transform = np.asarray(args.truth_transform, dtype=float).reshape(3, 3) if args.truth_transform is not None else None

    probe = load_navcalcs(probe_csv)
    tanker = load_navcalcs(tanker_csv)
    tspi = load_novatel_tspi(novatel_txt)

    merged = merge_probe_tanker_truth(probe, tanker, tspi, sync_tolerance=float(args.sync_tolerance))
    methods = [m for m in METHODS if method_available_in_merged(merged, m)]
    if not methods:
        raise RuntimeError("No complete pose methods found after merging probe/tanker navcalcs files.")

    merged = compute_vision_vectors(merged, methods, receiver_probe_to_antenna, tanker_center_to_antenna)
    merged = add_truth_vectors(merged, truth_transform)
    chosen_sign, sign_diag = choose_truth_sign(merged, methods, str(args.truth_sign))
    merged = add_errors(merged, methods, chosen_sign)
    err_summary = summarize_truth_errors(merged, methods)

    merged.to_csv(tables_dir / "merged_truth_comparison.csv", index=False)
    err_summary.to_csv(tables_dir / "truth_error_summary.csv", index=False)
    sign_diag.to_csv(tables_dir / "truth_sign_diagnostic.csv", index=False)
    write_markdown_table(err_summary, tables_dir / "truth_error_summary.md")
    write_markdown_table(sign_diag, tables_dir / "truth_sign_diagnostic.md")

    plot_tracking(merged, methods, plots_dir)
    plot_errors(merged, methods, plots_dir)
    plot_summary_bars(err_summary, plots_dir)

    summary_text = build_summary_text(
        probe_csv=probe_csv,
        tanker_csv=tanker_csv,
        novatel_txt=novatel_txt,
        df=merged,
        methods=methods,
        truth_sign=chosen_sign,
        sign_diag=sign_diag,
        err_summary=err_summary,
        sync_tolerance=float(args.sync_tolerance),
    )
    (out / "summary.txt").write_text(summary_text, encoding="utf-8")
    print(summary_text)
    print(f"\nWrote truth comparison to: {out}")


if __name__ == "__main__":
    main()
