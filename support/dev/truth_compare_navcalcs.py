def summarize_smoothness(df: pd.DataFrame, specs: Sequence[PoseSpec]) -> pd.DataFrame:
    rows: list[dict[str, object]] = []
    t = df["elapsed_s"].to_numpy(dtype=float)
    for spec in specs:
        valid = df[f"{spec.key}_truth_compare_valid"].to_numpy(dtype=bool)
        rng = df[f"{spec.key}_vision_range"].to_numpy(dtype=float)
        vec = numeric(df, [f"{spec.key}_vision_vec_x", f"{spec.key}_vision_vec_y", f"{spec.key}_vision_vec_z"])

        row: dict[str, object] = {
            "method": spec.label,
            "key": spec.key,
            "base_key": spec.base_key,
            "family": spec.family,
            "valid_samples": int(np.sum(valid)),
        }

        idx = np.where(valid & np.isfinite(t) & np.isfinite(rng) & finite_rows(vec))[0]
        if idx.size >= 2:
            dt = np.diff(t[idx])
            dr = np.diff(rng[idx])
            dv = np.diff(vec[idx], axis=0)
            good_dt = np.isfinite(dt) & (dt > 0.0)
            range_rate = np.full_like(dr, np.nan, dtype=float)
            vector_rate_norm = np.full_like(dr, np.nan, dtype=float)
            range_rate[good_dt] = dr[good_dt] / dt[good_dt]
            vector_rate_norm[good_dt] = vector_norm(dv[good_dt]) / dt[good_dt]
            append_stats(row, "range_step", dr)
            append_stats(row, "abs_range_step", np.abs(dr))
            append_stats(row, "range_rate", range_rate)
            append_stats(row, "abs_range_rate", np.abs(range_rate))
            append_stats(row, "vector_step_norm", vector_norm(dv))
            append_stats(row, "vector_rate_norm", vector_rate_norm)
        else:
            for name in ["range_step", "abs_range_step", "range_rate", "abs_range_rate", "vector_step_norm", "vector_rate_norm"]:
                append_stats(row, name, np.array([], dtype=float))
        rows.append(row)
    return pd.DataFrame(rows)


